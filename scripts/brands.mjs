/**
 * Writes brands/registry.generated.ts, the only place the app learns which
 * brands exist. A production build includes just the brand named by BRAND, so
 * no client's data ships in another client's site. Dev includes every brand.
 *
 * Also writes brands/routes.generated.ts for the dev-only /routes page: each
 * brand's work/strategy.ts and work/routes/<a|b|c>/route.ts. It is empty in a
 * production build.
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";

const root = new URL("../brands/", import.meta.url);
const all = readdirSync(root, { withFileTypes: true })
  .filter((entry) => entry.isDirectory() && existsSync(new URL(`${entry.name}/brand.ts`, root)))
  .map((entry) => entry.name)
  .sort();

const production = process.argv.includes("--production");
const selected = process.env.BRAND;

if (selected && !all.includes(selected)) {
  throw new Error(`BRAND="${selected}" has no folder in brands/. Found: ${all.join(", ")}.`);
}
if (production && !selected) {
  throw new Error(`Set BRAND to one of: ${all.join(", ")}.`);
}

const slugs = production ? [selected] : all;

// Marks are single-color drawings. Their color comes from CSS, so every fill and
// stroke becomes currentColor.
function readMarks(slug) {
  const dir = new URL(`${slug}/marks/`, root);
  return Object.fromEntries(
    readdirSync(dir)
      .filter((file) => file.endsWith(".svg"))
      .map((file) => {
        const svg = readFileSync(new URL(file, dir), "utf8")
          .replace(/<\?xml[^>]*\?>\s*/, "")
          .replace(/\s(width|height)="[^"]*"/g, "")
          .replace(/(fill|stroke)="(?!none)[^"]*"/g, '$1="currentColor"')
          .replace("<svg ", '<svg aria-hidden="true" focusable="false" ')
          .trim();
        return [file, svg];
      }),
  );
}

const ident = (slug) => slug.replace(/[^a-z0-9]/gi, "_");
const lines = [
  "// Generated by scripts/brands.mjs. Do not edit.",
  ...slugs.flatMap((slug) => [
    `import brand_${ident(slug)} from "./${slug}/brand";`,
    `import * as fonts_${ident(slug)} from "./${slug}/fonts";`,
  ]),
  "",
  "export const brands = {",
  ...slugs.map(
    (slug) =>
      `  ${JSON.stringify(slug)}: { brand: brand_${ident(slug)}, fonts: fonts_${ident(slug)}, marks: ${JSON.stringify(readMarks(slug))} as Record<string, string> },`,
  ),
  "};",
  "",
  `export const defaultSlug = ${JSON.stringify(selected ?? slugs[0])};`,
  "",
];

writeFileSync(new URL("registry.generated.ts", root), lines.join("\n"));

const withRoutes = production
  ? []
  : readdirSync(root, { withFileTypes: true })
      .filter((entry) => entry.isDirectory() && existsSync(new URL(`${entry.name}/work/strategy.ts`, root)))
      .map((entry) => {
        const dir = new URL(`${entry.name}/work/routes/`, root);
        const letters = existsSync(dir)
          ? readdirSync(dir).filter((l) => /^[abc]$/.test(l) && existsSync(new URL(`${l}/route.ts`, dir))).sort()
          : [];
        return { slug: entry.name, letters };
      });
const routeLines = [
  "// Generated by scripts/brands.mjs. Do not edit.",
  'import type { Route } from "@/lib/brand/route";',
  'import type { Strategy } from "@/lib/brand/schema";',
  ...withRoutes.flatMap(({ slug, letters }) => [
    `import strategy_${ident(slug)} from "./${slug}/work/strategy";`,
    ...letters.map((l) => `import route_${ident(slug)}_${l} from "./${slug}/work/routes/${l}/route";`),
  ]),
  "",
  "export const routeSets: Record<string, { strategy: Strategy; routes: Route[] }> = {",
  ...withRoutes.map(
    ({ slug, letters }) =>
      `  ${JSON.stringify(slug)}: { strategy: strategy_${ident(slug)}, routes: [${letters.map((l) => `route_${ident(slug)}_${l}`).join(", ")}] },`,
  ),
  "};",
  "",
];
writeFileSync(new URL("routes.generated.ts", root), routeLines.join("\n"));
console.log(`brands: ${slugs.join(", ")}${production ? " (production)" : ""}`);
